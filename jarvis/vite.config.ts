// `vite build --mode single` produces one self-contained index.html
// (used for the claude.ai Artifact); the default build is a normal PWA bundle.
export default defineConfig(({ mode }) => ({
  base: './',
  plugins: [react(), ...(mode === 'single' ? [viteSingleFile()] : [])],
  build: { outDir: mode === 'single' ? 'dist-single' : 'dist', chunkSizeWarningLimit: 2000 },
  test: { environment: 'node' },
}));
